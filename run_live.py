import os
from github import Github
from github_ingest import clone_repository
from orchestrator import Orchestrator

def push_to_github(file_path, new_content, finding_desc):
    """Milestone 5: Automates the Pull Request using PyGithub"""
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        print("Missing GITHUB_TOKEN. Cannot create Pull Request.")
        return

    try:
        g = Github(token)
        repo = g.get_repo("Ucneeraj/PatchForge-AI") # Your target repo
        
        # Create a new branch
        branch_name = f"patchforge-fix-{os.urandom(4).hex()}"
        main_branch = repo.get_branch("main")
        repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=main_branch.commit.sha)
        
        # Get the file to update
        contents = repo.get_contents(file_path, ref="main")
        commit_msg = f"Security Fix: {finding_desc}"
        
        # Push the patched file and open a PR
        repo.update_file(contents.path, commit_msg, new_content, contents.sha, branch=branch_name)
        pr = repo.create_pull(title=commit_msg, body="Automated security patch generated by PatchForge-AI.", head=branch_name, base="main")
        
        print(f"\n[SUCCESS] Pull Request automatically created: {pr.html_url}")
    except Exception as e:
        print(f"\n[ERROR] Failed to push to GitHub: {e}")

def main():
    repo_url = "https://github.com/Ucneeraj/PatchForge-AI.git"
    print(f"Starting Live PatchForge-AI pipeline for: {repo_url}")
    
    # 1. GitHub Ingestion (Milestone 1)
    local_path = clone_repository(repo_url)

    # 2. Run the Self-Healing Loop (Milestones 2, 3, & 4)
    print("\nInitiating Agents with Live Docker & LLM...")
    orchestrator = Orchestrator() 
    report = orchestrator.run_repo(source=local_path)

    # 3. User Validation Gate & PR (Milestone 5)
    print("\n" + "="*40 + "\nREPAIR OUTCOMES\n" + "="*40)
    
    if not report.outcomes:
        print("No vulnerabilities found or repaired.")
        return

    for outcome in report.outcomes:
        if outcome.success:
            print(f"\n[SUCCESS] Fixed vulnerability in: {outcome.finding.file_path}")
            print(f"Iterations used: {outcome.iterations_used}/3")
            print("Proposed Patch Diff:")
            print(outcome.final_diff)
            
            approval = input("\nDo you approve this patch for a Pull Request? (y/n): ")
            if approval.strip().lower() == 'y':
                print("Patch approved! Pushing to GitHub...")
                # We need the full patched file content here. If your outcome dataclass 
                # doesn't store the full new file text, you would read it from the local_path.
                # For this script, we assume outcome.replacement_code or reading from disk:
                with open(os.path.join(report.corrected_clone_path, outcome.finding.file_path), 'r') as f:
                    patched_file_content = f.read()
                push_to_github(outcome.finding.file_path, patched_file_content, outcome.finding.description)
            else:
                print("Patch rejected. Discarding changes.")
        else:
            print(f"\n[FAILED] Could not fix {outcome.finding.file_path} after {outcome.iterations_used} attempts.")

if __name__ == "__main__":
    main()